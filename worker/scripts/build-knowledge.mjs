// Turns docs/chat_knowledge/*.md into src/knowledge.js so the Worker needs no build step
// beyond this one. Run: npm run build:knowledge  (a test fails if the output is stale).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', 'docs', 'chat_knowledge');
const out = join(here, '..', 'src', 'knowledge.js');

export function buildKnowledge() {
  // Studio file first, then the apps in a fixed order, so the cached prompt never reshuffles.
  const order = ['kevro-apps.md', 'islamic-coloring.md', 'quraan-class.md', 'ayah-play.md'];
  const files = readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'README.md');
  const missing = order.filter((f) => !files.includes(f));
  if (missing.length) throw new Error('Missing knowledge files: ' + missing.join(', '));
  const extra = files.filter((f) => !order.includes(f)).sort();
  const text = [...order, ...extra]
    .map((f) => readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim())
    .join('\n\n---\n\n');
  return `// GENERATED by scripts/build-knowledge.mjs from docs/chat_knowledge. Do not edit.\nexport default ${JSON.stringify(text)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(out, buildKnowledge());
  console.log('Wrote', out);
}
